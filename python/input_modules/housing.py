"""Get households and housing stock by structure type."""

import logging

import numpy as np
import pandas as pd
import sqlalchemy as sql

from functools import lru_cache

import python.tests as tests
import python.utils as utils

generator = np.random.default_rng(utils.RANDOM_SEED)
logger = logging.getLogger(__name__)


def run_housing(
    year: int, population: pd.DataFrame, prior_housing_data: pd.DataFrame | None = None
) -> pd.DataFrame:
    """Orchestrator function to calculate households and housing units by structure type.

    This module generates households and housing units by structure type using
    SANDAG's Estimates Program data. For the launch year, both households and
    housing units by structure type are provided directly by SANDAG's Estimates
    Program.

    Subsequent years post-launch freeze mobile home households and
    housing units. Households by structure type, aka occupied housing units,
    are calculated by applying launch year proportions to the households
    generated by the formation rates module, excluding mobile homes. Housing
    units by structure type are then calculated by taking the occupied housing
    units by structure type and assuming launch year vacancy rates to calculate
    total housing units by structure type. Note that prior housing data is used
    for post-launch years to ensure that no housing units are lost within
    non-Mobile Home structure types.

    Optionally, controls can be applied post-launch as opposed to using the
    launch year totals, proportions, and rates to adjust:
        - The total mobile home households and housing units
        - The proportions of households by structure type
        - The vacancy rates by structure type

    Functionality is split apart for code encapsulation:
        _get_housing_inputs - Get households and housing units by structure
            type from SANDAG's Estimates Program
        _validate_housing_inputs - Validate inputs from the above function
        _create_housing_outputs - Create households and housing units by
            structure type
        _validate_housing_outputs - Validate the outputs from the above
            function
    """
    if year == utils.LAUNCH_YEAR:
        logger.info("Calculating housing for launch year")
        housing_inputs = _get_housing_inputs(year)
    else:
        logger.info("Calculating housing for post-launch year")
        housing_inputs = _get_housing_inputs(utils.LAUNCH_YEAR)
    _validate_housing_inputs(housing_inputs)

    housing_outputs = _create_housing_outputs(
        housing_inputs=housing_inputs,
        population=population,
        year=year,
        prior_housing_data=prior_housing_data,
    )
    _validate_housing_outputs(housing_outputs)

    return housing_outputs


# Decorator to cache the results of the function to improve performance
# As it is called repeatedly for post-launch years if no controls are given
@lru_cache(maxsize=1)
def _get_housing_inputs(year: int) -> pd.DataFrame:
    """Load input datasets for households and housing units by structure type."""
    with utils.ESTIMATES_ENGINE.connect() as connection:
        with open(utils.SQL_FOLDER / "housing" / "get_housing.sql") as file:
            return pd.read_sql_query(
                sql=sql.text(file.read()),
                con=connection,
                params={
                    "run_id": utils.ESTIMATES_RUN_ID,
                    "year": year,
                },  # type: ignore
            )


def _validate_housing_inputs(
    housing_inputs: pd.DataFrame,
) -> None:
    """Validate the input datasets for households and housing units by structure type."""
    # Validate households and housing units by structure type
    tests.validate_data(
        table_name="Input Households and Housing Units by Structure Type",
        data=housing_inputs,
        row_count={"key_columns": {"structure_type"}},
        negative={},
        null={"null_ok": {"hh_pct", "vacancy_rate"}},
    )


def _create_housing_outputs(
    housing_inputs: pd.DataFrame,
    population: pd.DataFrame,
    year: int,
    prior_housing_data: pd.DataFrame | None = None,
) -> pd.DataFrame:
    """Create households and housing units by structure type."""
    housing = housing_inputs

    if year == utils.LAUNCH_YEAR:
        return housing[["structure_type", "hs", "hh"]]
    elif utils.HOUSING_CONTROLS is not None:
        # Get housing controls for the increment
        controls = utils.HOUSING_CONTROLS.loc[utils.HOUSING_CONTROLS["year"] == year]

        # Extract the Mobile Home housing data separately as it is kept constant
        housing_mh = pd.DataFrame(
            {
                "structure_type": ["Mobile Home"],
                "hh": [controls["hh_mh"].sum()],
                "hs": [controls["hs_mh"].sum()],
            }
        )

        # Check the Mobile Home households control is not greater
        # Than the total households from the formed households population
        hh_mh = controls["hh_mh"].sum()
        if hh_mh > population["hh"].sum():
            raise ValueError("Mobile Home households control exceeds total households")
        # Get the total households ignoring Mobile Homes, from the controls
        total_hh_non_mh = population["hh"].sum() - hh_mh

        # Apply household structure type proportions from the controls
        # And integerize preserving total non-Mobile Home households
        hh_mf, hh_sf = utils.integerize_1d(
            data=pd.Series(
                [
                    controls["hh_mf_pct"].sum() * total_hh_non_mh,
                    controls["hh_sf_pct"].sum() * total_hh_non_mh,
                ]
            ),
            control=total_hh_non_mh,
            methodology="weighted_random",
            generator=generator,
        )

        # Calculate housing units using vacancy rates provided by controls
        hs_mf = round(hh_mf / (1 - controls["vr_mf"].sum()))
        hs_sf = round(hh_sf / (1 - controls["vr_sf"].sum()))

        # Combine the calculated households and housing units into a DataFrame
        housing_non_mh = pd.DataFrame(
            {
                "structure_type": ["Multifamily", "Single Family"],
                "hh": [hh_mf, hh_sf],
                "hs": [hs_mf, hs_sf],
            }
        )

    else:
        # Extract the Mobile Home housing data separately as it is kept constant
        housing_mh = housing.loc[housing["structure_type"] == "Mobile Home"][
            ["structure_type", "hs", "hh"]
        ]

        # Get the total households from the formed households population
        # And apply structure type proportions ignoring Mobile Homes as those are kept constant
        hh_mh = housing.loc[housing["structure_type"] == "Mobile Home", "hh"].sum()
        total_hh_non_mh = population["hh"].sum() - hh_mh

        hh_non_mh = housing.loc[housing["structure_type"] != "Mobile Home"].assign(
            hh=lambda x: x["hh_pct"] * total_hh_non_mh
        )[["structure_type", "hh"]]

        hh_non_mh["hh"] = utils.integerize_1d(
            data=hh_non_mh["hh"],
            control=total_hh_non_mh,
            methodology="weighted_random",
            generator=generator,
        )

        # Calculate housing units by structure type to match vacancy-adjusted households
        # Again ignoring Mobile Homes as those are kept constant
        housing_non_mh = hh_non_mh.merge(
            right=housing[["structure_type", "vacancy_rate"]], on="structure_type"
        ).assign(hs=lambda x: x["hh"] / (1 - x["vacancy_rate"]))[
            ["structure_type", "hs", "hh"]
        ]

        housing_non_mh["hs"] = utils.integerize_1d(
            data=housing_non_mh["hs"],
            control=round(housing_non_mh["hs"].sum()),
            methodology="weighted_random",
            generator=generator,
        )

    # Use the prior year housing data to ensure no housing units are lost
    # For non-Mobile Home structure types
    # Households are included in the max function to avoid edge-cases
    # Where the calculated housing units may be less than the number of households
    if prior_housing_data is not None:
        prior_housing_non_mh = prior_housing_data.loc[
            prior_housing_data["structure_type"] != "Mobile Home"
        ][["structure_type", "hs"]]
        housing_non_mh = housing_non_mh.merge(
            right=prior_housing_non_mh, on="structure_type", suffixes=("", "_prior")
        ).assign(hs=lambda x: x[["hs", "hs_prior", "hh"]].max(axis=1))[
            ["structure_type", "hs", "hh"]
        ]
    else:
        raise ValueError("No prior year housing data provided post-launch year")

    # Return the calculated households and housing units by structure type
    # Adding back in the held-constant Mobile Home housholds and housing units
    return pd.concat(
        [
            housing_non_mh,
            housing_mh,
        ],
        ignore_index=True,
    ).sort_values(by="structure_type")


def _validate_housing_outputs(housing_outputs: pd.DataFrame) -> None:
    """Validate the output households and housing units by structure type."""
    # Validate households and housing units by structure type
    tests.validate_data(
        table_name="Output Households and Housing Units by Structure Type",
        data=housing_outputs,
        row_count={"key_columns": {"structure_type"}},
        negative={},
        null={},
    )
